import { expect, test } from '@playwright/test'

test('task lifecycle, schedule, status history, and browser persistence', async ({ page }) => {
  await page.goto('/work?new=1')
  const createDialog = page.getByRole('dialog', { name: 'Create a task' })
  await expect(createDialog).toBeVisible()
  await page.getByLabel('Task title *').fill('Smoke test: controller notes')
  await createDialog.locator('select').nth(0).selectOption('dc-motor-pid')
  await page.getByLabel('Planned start date').fill('2026-11-03')
  await page.getByLabel('Planned start time').fill('09:15')
  await page.getByLabel('Target completion date').fill('2026-11-08')
  await page.getByLabel('Target completion time').fill('16:30')
  await page.getByRole('button', { name: 'Create task' }).click()

  const taskTitle = page.getByRole('button', { name: 'Smoke test: controller notes' })
  await expect(taskTitle).toBeVisible()
  await taskTitle.click()
  const detail = page.getByRole('dialog', { name: 'Smoke test: controller notes' })
  await expect(detail.getByText('3 Nov 2026')).toBeVisible()
  await expect(detail.getByText('8 Nov 2026')).toBeVisible()
  await detail.getByRole('button', { name: 'Start task' }).click()
  await expect(detail.locator('.detail-item').filter({ hasText: 'Actual start' })).not.toContainText('Not recorded')
  await detail.getByRole('button', { name: 'Mark complete' }).click()
  await expect(detail.locator('.record-banner')).toContainText('Completed')
  await expect(detail.locator('.detail-item').filter({ hasText: 'Actual completion' })).not.toContainText('Not recorded')
  await detail.getByRole('button', { name: 'Reopen' }).click()
  await expect(detail.locator('.record-banner')).toContainText('In Progress')
  await expect(detail.locator('.history-block')).toContainText('Completed')
  await detail.getByRole('button', { name: 'Close dialog' }).click()

  await page.reload()
  await page.getByRole('button', { name: 'Smoke test: controller notes' }).click()
  const persisted = page.getByRole('dialog', { name: 'Smoke test: controller notes' })
  await expect(persisted.locator('.record-banner')).toContainText('In Progress')
  await expect(persisted.locator('.detail-item').filter({ hasText: 'Actual completion' })).not.toContainText('Not recorded')
  await expect(persisted.locator('.history-block')).toContainText('Completed')
})

test('evidence upload validation, preview, and removal', async ({ page }) => {
  await page.goto('/work?new=1')
  await page.getByLabel('Task title *').fill('Smoke test: evidence attachment')
  await page.getByRole('button', { name: 'Create task' }).click()
  await page.getByRole('button', { name: 'Smoke test: evidence attachment' }).click()
  const detail = page.getByRole('dialog', { name: 'Smoke test: evidence attachment' })
  await detail.getByRole('button', { name: 'Add evidence' }).click()

  const fileInput = detail.locator('input[name="evidence-file"]')
  await fileInput.setInputFiles({ name: 'invalid.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('not supported') })
  await detail.getByRole('button', { name: 'Attach evidence' }).click()
  await expect(detail.getByRole('alert')).toContainText('not supported')

  await detail.getByLabel('Evidence title').fill('Test measurement data')
  await fileInput.setInputFiles({ name: 'motor-response.csv', mimeType: 'text/csv', buffer: Buffer.from('time,response\n0,0\n1,1') })
  await detail.getByRole('button', { name: 'Attach evidence' }).click()
  const evidenceCard = detail.locator('.evidence-card').filter({ hasText: 'Test measurement data' })
  await expect(evidenceCard).toBeVisible()
  await expect(evidenceCard.getByRole('link', { name: /Open \/ download/ })).toBeVisible()

  page.once('dialog', dialog => dialog.accept())
  await evidenceCard.getByRole('button', { name: 'Remove Test measurement data' }).click()
  await expect(detail.locator('.evidence-card')).toHaveCount(0)
})

test('navigation, project report flow, and mobile menu', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Building toward better control.' })).toBeVisible()
  await page.getByRole('link', { name: 'Career roadmap', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Career roadmap' })).toBeVisible()
  await page.getByRole('link', { name: 'Technical skills' }).click()
  await expect(page.getByRole('heading', { name: 'Technical skills' })).toBeVisible()
  await page.getByRole('link', { name: 'Projects' }).click()
  await expect(page.getByRole('heading', { name: 'Projects', exact: true })).toBeVisible()
  await page.locator('.project-card').filter({ hasText: 'DC motor modelling and PID control' }).getByRole('button', { name: 'Open project details' }).click()
  await expect(page.getByRole('heading', { name: 'DC motor modelling and PID control' })).toBeVisible()
  await page.getByRole('button', { name: 'Add report' }).click()
  await page.getByLabel('Report title *').fill('Smoke test report')
  await page.getByLabel('Report status').selectOption('Published')
  await page.getByRole('button', { name: 'Save report' }).click()
  await expect(page.locator('.report-list')).toContainText('Smoke test report')

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await expect(page.locator('.sidebar')).toHaveClass(/sidebar-open/)
  await page.getByRole('link', { name: 'About' }).click()
  await expect(page.getByRole('heading', { name: 'About Allen' })).toBeVisible()
  await expect(page.locator('.sidebar')).not.toHaveClass(/sidebar-open/)
})
